import {writeFileSync} from 'node:fs';
import path from 'node:path';
import type {LoadedProject} from '../config/types';
import {sha256File} from '../media/hash';
import {
  assertSafePath,
  ensureSafeDirectory,
  safeRecreateDirectory,
  type WriteBoundary,
} from '../workspace/writeBoundary';

export type StagedSceneModule = {
  id: string;
  sourcePath: string;
  stagedFileName: string;
  sha256: string;
};

export type StagedProjectBundle = {
  engineBundleDir: string;
  entryPoint: string;
  modulesDir: string;
  bundleDir: string;
  modules: StagedSceneModule[];
};

const ENTRY_FILE = 'entry.tsx';

const importLines = (modules: readonly StagedSceneModule[]): string =>
  modules
    .map(
      (module, index) =>
        `import * as sceneModule${index} from './modules/${module.stagedFileName}';`,
    )
    .join('\n');

const importedModules = (modules: readonly StagedSceneModule[]): string =>
  modules
    .map((_, index) => `sceneModule${index}.default ?? sceneModule${index}.sceneModule`)
    .join(',\n  ');

const entryContents = (
  project: LoadedProject,
  modules: readonly StagedSceneModule[],
): string => {
  const bindings = project.sceneModules.map((module) => ({
    id: module.id,
    contractVersion: module.contractVersion,
    moduleType: module.moduleType,
    sha256: module.sha256,
    canvas: module.canvas,
    samplingFps: module.samplingFps,
    pixelated: module.pixelated,
    styleIds: module.styleIds,
  }));
  const approvedAssetIds = project.assets
    .filter((asset) => asset.approval === 'approved')
    .map((asset) => asset.id);
  return `// Generated by MVFoundry inside the external project cache. Do not commit.
import {Composition, registerRoot} from 'remotion';
import {FactoryFilm} from '@mvfoundry/remotion/FactoryFilm';
import {DEFAULT_RENDER_PROJECT} from '@mvfoundry/remotion/defaultProject';
import {bindProjectSceneModules} from '@mvfoundry/scenes/external/contract';
${importLines(modules)}

const projectRenderers = bindProjectSceneModules(
  ${JSON.stringify(bindings, null, 2)},
  [
  ${importedModules(modules)}
  ],
  ${JSON.stringify(approvedAssetIds)},
);

const ProjectFilm = (props: {project: import('@mvfoundry/config/types').RenderProjectSnapshot}) => (
  <FactoryFilm project={props.project} extraRenderers={projectRenderers} />
);

const FactoryRoot = () => (
  <Composition
    id="MV-Factory"
    component={ProjectFilm}
    defaultProps={{project: DEFAULT_RENDER_PROJECT}}
    durationInFrames={DEFAULT_RENDER_PROJECT.output.durationInFrames}
    fps={DEFAULT_RENDER_PROJECT.output.fps}
    width={DEFAULT_RENDER_PROJECT.output.width}
    height={DEFAULT_RENDER_PROJECT.output.height}
    calculateMetadata={({props}) => ({
      durationInFrames: props.project.output.durationInFrames,
      fps: props.project.output.fps,
      width: props.project.output.width,
      height: props.project.output.height,
    })}
  />
);

registerRoot(FactoryRoot);
`;
};

/**
 * Copies hash-verified module bytes into <project>/cache/engine-bundle and
 * writes a static entry that imports those copies. The repository is never a
 * staging location and the original module files stay untouched.
 */
export const stageProjectBundle = (
  project: LoadedProject,
  options: {boundary: WriteBoundary},
): StagedProjectBundle => {
  const {boundary} = options;
  const engineBundleDir = safeRecreateDirectory(
    boundary,
    path.join(boundary.cacheRoot, 'engine-bundle'),
  );
  const modulesDir = ensureSafeDirectory(boundary, path.join(engineBundleDir, 'modules'), 'cache');
  const bundleDir = ensureSafeDirectory(boundary, path.join(engineBundleDir, 'bundle'), 'cache');

  const modules: StagedSceneModule[] = project.sceneModules.map((module, index) => {
    const extension = path.extname(module.path).toLowerCase();
    const stagedFileName = `${String(index).padStart(3, '0')}-${module.id}${extension}`;
    const target = assertSafePath(boundary, path.join(modulesDir, stagedFileName), {
      expect: 'file',
      subtree: 'cache',
    });
    writeFileSync(target, module.sourceBytes);
    const stagedHash = sha256File(target);
    if (stagedHash !== module.sha256) {
      throw new Error(`Staged scene module hash mismatch for ${module.id}`);
    }
    return {
      id: module.id,
      sourcePath: module.path,
      stagedFileName,
      sha256: stagedHash,
    };
  });

  const entryPoint = assertSafePath(boundary, path.join(engineBundleDir, ENTRY_FILE), {
    expect: 'file',
    subtree: 'cache',
  });
  writeFileSync(entryPoint, entryContents(project, modules), 'utf8');

  return {engineBundleDir, entryPoint, modulesDir, bundleDir, modules};
};
