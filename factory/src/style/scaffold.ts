// Style-aware project scaffolding.
//
// A visual style is not a renderer: a style-driven project still needs a
// project-local Canvas module that declares the style. This module centralises
// the safe attachment contract so the CLI and tests cannot drift apart.
//
// Creating a scaffold is NOT approval. Only `mv-project attach-style
// --approve-module` may turn a reviewed scaffold (or a user-supplied module)
// into a manifest entry.

import type {ProjectConfig, SceneModuleConfig} from '../config/types';
import {ConfigValidationError} from '../errors';
import {assertRegisteredStyle} from './catalog';

export const STYLE_SCAFFOLD_MODULE_ID = 'style-gallery';
export const STYLE_SCAFFOLD_RELATIVE_PATH = 'scenes/style-gallery.ts';

const MODULE_ID_PATTERN = /^[a-z0-9][a-z0-9-]{2,63}$/;
const SHA256_PATTERN = /^[a-f0-9]{64}$/;

const fail = (message: string): never => {
  throw new ConfigValidationError(message);
};

/**
 * A project module path must stay inside the project's `scenes/` directory.
 * Filesystem containment and link rejection are enforced separately by the
 * write boundary; this only validates the declared shape.
 */
export const assertStyleModulePath = (modulePath: string): string => {
  if (typeof modulePath !== 'string' || modulePath.trim() === '') {
    fail('style module path must be a non-empty string');
  }
  const raw = modulePath.trim();
  if (/^[a-zA-Z]:/.test(raw) || raw.startsWith('/') || raw.startsWith('\\')) {
    fail('style module path must be project-relative');
  }
  const segments = raw.replace(/\\/g, '/').split('/');
  if (segments.some((segment) => segment === '' || segment === '.' || segment === '..')) {
    fail('style module path must not contain empty, current or parent segments');
  }
  if (segments.some((segment) => segment.includes(':'))) {
    fail('style module path must not contain drive or alternate-stream syntax');
  }
  if (segments[0] !== 'scenes' || segments.length < 2) {
    fail('style module path must point inside the project scenes/ directory');
  }
  const fileName = segments[segments.length - 1];
  if (!/\.(ts|tsx)$/i.test(fileName) || /\.d\.ts$/i.test(fileName)) {
    fail('style module path must be a .ts or .tsx implementation file');
  }
  return segments.join('/');
};

/**
 * A short, stable header written above the shared gallery template so a
 * generated scaffold cannot be mistaken for an approved production scene.
 */
export const styleScaffoldHeader = (styleId: string): string => {
  const profile = assertRegisteredStyle(styleId);
  return [
    `// Project scene scaffold generated by mv-project init --style-id ${styleId}.`,
    `// Style: ${profile.label} — ${profile.intent}`,
    '// This file is NOT approved automatically. Review it, then run:',
    `//   mv-project attach-style --project <id> --workspace <root> --style-id ${styleId} --module ${STYLE_SCAFFOLD_RELATIVE_PATH} --approve-module`,
    '',
  ].join('\n');
};

export type StyleAttachmentInput = {
  styleId: string;
  /** Project-relative path under scenes/. */
  modulePath: string;
  sha256: string;
  /** Manifest module id; must match the module's exported `id`. */
  moduleId?: string;
  /** Optional reviewer note recorded as `visual.style.note`. */
  note?: string;
};

/**
 * Applies an explicitly approved module as the selected style.
 *
 * The caller must have obtained explicit human approval for the exact module
 * bytes before calling this function. The function itself records that
 * decision as `trust: "user-authored-approved"`; it does not verify it.
 *
 * Attaching a style is allowed only on an untouched timeline. Re-planning or
 * changing the style after shots exist needs an explicit new revision, not a
 * silent manifest rewrite.
 */
export const applyStyleAttachment = (
  config: ProjectConfig,
  input: StyleAttachmentInput,
): ProjectConfig => {
  const profile = assertRegisteredStyle(input.styleId);
  if (!profile.implementedBackends.includes('canvas2d')) {
    fail(
      `visual style ${input.styleId} is not implemented by any available backend in this phase; implemented: ${profile.implementedBackends.join(', ')}`,
    );
  }
  if (config.chapters.length > 0) {
    fail('style attachment requires an empty timeline; attach before planning or edit project.json explicitly');
  }
  if (config.visual.style !== undefined) {
    fail(`project already selects visual style ${config.visual.style.id}; refusing to replace it silently`);
  }
  const modulePath = assertStyleModulePath(input.modulePath);
  const moduleId = input.moduleId ?? STYLE_SCAFFOLD_MODULE_ID;
  if (!MODULE_ID_PATTERN.test(moduleId)) {
    fail(`style module id must be lowercase letters, digits and hyphens (3-64 chars): ${moduleId}`);
  }
  if (!SHA256_PATTERN.test(input.sha256)) {
    fail('style module sha256 must be lowercase hex');
  }
  if (config.sceneModules.some((module) => module.id === moduleId)) {
    fail(`sceneModules already declares module id ${moduleId}`);
  }
  if (config.sceneModules.some((module) => module.path === modulePath)) {
    fail(`sceneModules already declares module path ${modulePath}`);
  }

  const styleModule: SceneModuleConfig = {
    id: moduleId,
    path: modulePath,
    moduleType: 'canvas2d',
    contractVersion: 1,
    sha256: input.sha256,
    trust: 'user-authored-approved',
    canvas: {mode: 'output'},
    samplingFps: 'output',
    pixelated: false,
    label: `${profile.label} scaffold`,
    description: `Project-local module reviewed and approved for visual style ${input.styleId}.`,
    styleIds: [input.styleId],
  };

  return {
    ...config,
    visual: {
      ...config.visual,
      styleProfile: input.styleId,
      defaultRenderer: `project:${moduleId}`,
      style: {
        id: input.styleId,
        ...(input.note ? {note: input.note} : {}),
      },
    },
    sceneModules: [...config.sceneModules, styleModule],
  };
};