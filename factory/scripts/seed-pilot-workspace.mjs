// Seeds fresh synthetic projects for the pilot-admission acceptance suite:
// an ordinary P0 project, a scoped pilot project, a two-job concurrency project
// and a full fake-provider lifecycle project.
//
// Every byte is generated procedurally. No provider is contacted, no credential
// is required and no production media is copied.
//
// Usage: npm run pilot:seed
//        node factory/scripts/seed-pilot-workspace.mjs --root <external-root>
// Requires FFmpeg for the synthetic clips.

import {existsSync, mkdirSync, realpathSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {
  sha256,
  writeIncompatibleClip,
  writeJson,
  writePlatePng,
  writeWav,
} from './support/synthetic-media.mjs';

const require = createRequire(import.meta.url);
const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, '..', '..');
const {isInside} = require('../dist/src/workspace/guard.js');
const {RUNWAY_PRICING_SNAPSHOT, computeSnapshotHash} = require('../dist/src/generation/pricing.js');

const args = process.argv.slice(2);
const rootArg = args.includes('--root') ? args[args.indexOf('--root') + 1] : undefined;
const rawRoot = rootArg ?? process.env.MV_WORKSPACE_ROOT;
if (!rawRoot) {
  console.error('MV_WORKSPACE_ROOT or --root is required');
  process.exit(2);
}

const engineRoot = realpathSync(repoRoot);
let ancestor = path.resolve(rawRoot);
while (!existsSync(ancestor)) {
  const parent = path.dirname(ancestor);
  if (parent === ancestor) break;
  ancestor = parent;
}
if (isInside(engineRoot, realpathSync(ancestor)) || isInside(realpathSync(ancestor), engineRoot)) {
  throw new Error('Pilot workspace must be outside and must not contain the engine repository');
}
mkdirSync(rawRoot, {recursive: true});
const workspaceRoot = realpathSync(rawRoot);
if (isInside(engineRoot, workspaceRoot) || isInside(workspaceRoot, engineRoot)) {
  throw new Error('Pilot workspace must be outside and must not contain the engine repository');
}

