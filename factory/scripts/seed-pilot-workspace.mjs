/** A pricing snapshot fixture with a correct content hash for its mutated body. */
const writePricingFixture = (target, name, mutate) => {
  const base = {
    ...RUNWAY_PRICING_SNAPSHOT,
    retrievedAt: new Date().toISOString(),
    ...mutate(RUNWAY_PRICING_SNAPSHOT),
  };
  const {snapshotSha256: _ignored, ...rest} = base;
  writeJson(path.join(target, 'generation', 'fixtures', name), {
    ...rest,
    snapshotSha256: computeSnapshotHash(rest),
  });
};

