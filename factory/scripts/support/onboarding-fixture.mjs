// Synthetic inputs for the onboarding acceptance project.
//
// Everything here is deterministic and generated locally. No song, image or
// clip from a real production is involved, and nothing is written into the
// engine repository.

import {mkdirSync, writeFileSync} from 'node:fs';
import path from 'node:path';
import {
  sha256,
  writeAlphaPng,
  writeMovingClip,
  writeOpaqueRgbPng,
} from './synthetic-media.mjs';

export const ONBOARDING_FPS = 30;
export const ONBOARDING_SECONDS = 30;
export const ONBOARDING_FRAMES = ONBOARDING_SECONDS * ONBOARDING_FPS; // 900

/** Four nonuniform sections; frames are half-open. */
export const ONBOARDING_SECTIONS = [
  {id: 'SEC-01', label: 'first light', startFrame: 0, endFrame: 180, pulse: 1, amplitude: 0.22},
  {id: 'SEC-02', label: 'the street', startFrame: 180, endFrame: 480, pulse: 0.5, amplitude: 0.3},
  {id: 'SEC-03', label: 'crossing', startFrame: 480, endFrame: 720, pulse: 0.25, amplitude: 0.42},
  {id: 'SEC-04', label: 'after', startFrame: 720, endFrame: 900, pulse: 0.75, amplitude: 0.2},
];

/** Pulses land on these seconds, so every cut cue is on a real transient. */
export const ONBOARDING_CUT_SECONDS = [3, 11, 20, 27];

const PLATE_COLOURS = [
  [30, 60, 150],
  [20, 130, 90],
  [160, 40, 70],
  [90, 60, 150],
  [150, 110, 30],
  [35, 115, 130],
];

const writeScore = (file) => {
  const sampleRate = 48000;
  const channels = 2;
  const frames = ONBOARDING_SECONDS * sampleRate;
  const dataSize = frames * channels * 2;
  const buffer = Buffer.alloc(44 + dataSize);
  buffer.write('RIFF', 0);
  buffer.writeUInt32LE(36 + dataSize, 4);
  buffer.write('WAVE', 8);
  buffer.write('fmt ', 12);
  buffer.writeUInt32LE(16, 16);
  buffer.writeUInt16LE(1, 20);
  buffer.writeUInt16LE(channels, 22);
  buffer.writeUInt32LE(sampleRate, 24);
  buffer.writeUInt32LE(sampleRate * channels * 2, 28);
  buffer.writeUInt16LE(channels * 2, 32);
  buffer.writeUInt16LE(16, 34);
  buffer.write('data', 36);
  buffer.writeUInt32LE(dataSize, 40);
  const fade = Math.round(sampleRate * 0.02);
  for (let index = 0; index < frames; index++) {
    const second = index / sampleRate;
    const section =
      ONBOARDING_SECTIONS.find((entry) => {
        const frame = Math.floor(second * ONBOARDING_FPS);
        return frame >= entry.startFrame && frame < entry.endFrame;
      }) ?? ONBOARDING_SECTIONS[ONBOARDING_SECTIONS.length - 1];
    const period = Math.round(sampleRate * section.pulse);
    const inPulse = index % period < Math.round(sampleRate / 12);
    const envelope = Math.min(1, index / fade, (frames - index) / fade);
    const tone = Math.sin(2 * Math.PI * (section.startFrame === 480 ? 176 : 220) * second);
    const value = Math.max(
      -1,
      Math.min(1, tone * 0.12 * envelope + (inPulse ? section.amplitude : 0) * envelope),
    );
    const sample = Math.round(value * 32767);
    buffer.writeInt16LE(sample, 44 + index * 4);
    buffer.writeInt16LE(sample, 46 + index * 4);
  }
  mkdirSync(path.dirname(file), {recursive: true});
  writeFileSync(file, buffer);
};

/**
 * Writes every onboarding input into `root` and returns the manifest the
 * acceptance verifier asserts against.
 */
export const writeOnboardingInputs = (root) => {
  mkdirSync(root, {recursive: true});
  const score = path.join(root, 'score-30s.wav');
  writeScore(score);

  const plates = PLATE_COLOURS.map((colour, index) => {
    const file = path.join(root, `plate-0${index + 1}.png`);
    writeOpaqueRgbPng(file, 640, 360, colour, {from: 0.35 + index * 0.05, to: 0.5 + index * 0.05});
    return {id: `PLATE-0${index + 1}`, file, rgb: colour, sha256: sha256(file), colourType: 2};
  });

  const layer = path.join(root, 'layer-01.png');
  writeAlphaPng(layer, 640, 360, (x, y) => {
    const dx = x - 320;
    const dy = y - 180;
    const inside = dx * dx + dy * dy < 95 * 95;
    return inside ? [40, 240, 220, 235] : [0, 0, 0, 0];
  });

  const clip = path.join(root, 'clip-01.mp4');
  writeMovingClip(clip, {
    width: 640,
    height: 360,
    seconds: 12,
    fps: ONBOARDING_FPS,
    from: [18, 24, 44],
    to: [230, 120, 60],
    audioTone: 440,
    bandSpeed: 1.2,
    columns: 5,
  });

  const metadata = path.join(root, 'metadata.json');
  writeFileSync(
    metadata,
    `${JSON.stringify(
      {
        title: '雨夜霓虹 · Neon Rain (合成验收)',
        artist: 'MVFoundry 내부 테스트 · ネオン',
        source: 'Deterministic synthetic score generated by factory/scripts/support/onboarding-fixture.mjs',
        rights: 'Synthetic fixture; no third-party rights, no real song, 🌧️',
        styleProfile: 'neon-rain-fixture',
      },
      null,
      2,
    )}\n`,
    'utf8',
  );

  return {
    root,
    score,
    plates,
    layer,
    clip,
    metadata,
    sections: ONBOARDING_SECTIONS,
    cutCues: ONBOARDING_CUT_SECONDS.map((seconds) => ({
      seconds,
      frame: Math.round(seconds * ONBOARDING_FPS),
    })),
    hashes: {
      score: sha256(score),
      layer: sha256(layer),
      clip: sha256(clip),
      metadata: sha256(metadata),
    },
    fps: ONBOARDING_FPS,
    durationFrames: ONBOARDING_FRAMES,
  };
};