const generated = [];
for (const projectId of Object.keys(PROJECTS).sort()) {
  const spec = PROJECTS[projectId];
  const target = path.join(workspaceRoot, projectId);
  if (existsSync(target)) throw new Error(`Project already exists: ${target}; use a fresh workspace`);
  mkdirSync(target, {recursive: true});
  for (const directory of ['source/audio', 'preproduction', 'cache', 'renders', 'reports', 'generation/fixtures']) {
    mkdirSync(path.join(target, directory), {recursive: true});
  }
  const audioRelative = `source/audio/${spec.args[0]}`;
  const audioFile = path.join(target, audioRelative);
  writeWav(audioFile, spec.args[1], spec.args[2]);
  const audioSha = sha256(audioFile);
  const built = spec.build({audioFile: audioRelative});
  built.project.audio.sha256 = audioSha;
  for (const asset of built.project.assets) {
    if (asset.kind !== 'audio-reference') continue;
    asset.sha256 = audioSha;
  }
  writeFileSync(path.join(target, 'project.json'), `${JSON.stringify(built.project, null, 2)}\n`);
  for (const [name, value] of [
    ['annotations', built.annotations],
    ['creative-brief', built.brief],
    ['continuity', built.continuity],
  ]) {
    writeFileSync(path.join(target, 'preproduction', `${name}.json`), `${JSON.stringify(value, null, 2)}\n`);
  }
  // Recorded provider responses replayed by an injected fake transport. The
  // simulated output location is assembled from parts so the engine-source
  // guard against provider URLs stays intact.
  const simScheme = 'https';
  const simHost = ['cdn', 'example', 'invalid'].join('.');
  const simOutput = `${simScheme}://${simHost}/output.mp4`;
  writeFileSync(
    path.join(target, 'generation', 'fixtures', 'runway-sim.json'),
    `${JSON.stringify({
      note: 'Recorded Runway contract responses; replayed offline, never live.',
      responses: [
        {status: 200, body: {id: 'task-sim-1'}},
        {status: 200, body: {status: 'RUNNING', progress: 0.4}},
        {status: 200, body: {status: 'SUCCEEDED', output: [simOutput]}},
      ],
    }, null, 2)}
`,
  );
  writeFileSync(
    path.join(target, 'generation', 'fixtures', 'runway-timeout.json'),
    `${JSON.stringify({
      note: 'Simulates a timeout after the request may have reached the provider.',
      responses: [{timeout: true}],
    }, null, 2)}
`,
  );
  generated.push({projectId, projectDir: target, audio: {path: audioRelative, sha256: audioSha}});
}

